#!/usr/bin/env python3
"""
convert_cora_to_mdb.py - Converts Cora (LINQS format) to MillenniumDB GQL format

The Cora dataset is a citation network of 2,708 machine learning papers classified
into 7 categories. Each paper has a 1,433-dimensional bag-of-words feature vector.

IMPORTANT: MillenniumDB uses a compact line-by-line import format, NOT standard GQL syntax.

Usage:
    python convert_cora_to_mdb.py [cora_dir] [output_file] [max_features]

    cora_dir:      Directory containing cora.content and cora.cites (default: /tmp/cora_dataset/cora)
    output_file:   Output .gql file path (default: cora.gql)
    max_features:  Number of features to include, 1-1433 (default: 16 for quick tests)

Examples:
    # Quick test (16 features)
    python convert_cora_to_mdb.py ~/Descargas/cora/cora ./data/example/gql/cora/cora.gql

    # Full features (1433 dimensions)
    python convert_cora_to_mdb.py ~/Descargas/cora/cora ./data/example/gql/cora/cora_full.gql 1433
"""

import os
import sys
from typing import Dict, Set, List, Tuple

# Class labels in Cora dataset mapped to integer IDs
CLASS_MAP = {
    'Case_Based': 0,
    'Genetic_Algorithms': 1,
    'Neural_Networks': 2,
    'Probabilistic_Methods': 3,
    'Reinforcement_Learning': 4,
    'Rule_Learning': 5,
    'Theory': 6
}

def parse_content_file(content_file: str, max_features: int) -> Tuple[Dict[str, int], List[Tuple[int, str, int, str, List[int]]]]:
    """
    Parse cora.content file and extract node information.

    Returns:
        - paper_id_map: mapping from original paper_id to sequential index
        - nodes: list of (index, paper_id, label, class_name, features)
    """
    paper_id_map: Dict[str, int] = {}
    nodes: List[Tuple[int, str, int, str, List[int]]] = []

    with open(content_file, 'r') as f:
        for idx, line in enumerate(f):
            parts = line.strip().split('\t')
            if len(parts) < 3:
                continue

            paper_id = parts[0]
            features = [int(x) for x in parts[1:-1]][:max_features]
            class_name = parts[-1]
            label = CLASS_MAP.get(class_name, -1)

            paper_id_map[paper_id] = idx
            nodes.append((idx, paper_id, label, class_name, features))

    return paper_id_map, nodes


def parse_cites_file(cites_file: str, paper_id_map: Dict[str, int]) -> List[Tuple[int, int]]:
    """
    Parse cora.cites file and extract edge information.

    The format is: <cited_paper_id>\t<citing_paper_id>
    This means: citing_paper -> cited_paper (citing paper references the cited one)

    Returns:
        - edges: list of (from_idx, to_idx) representing CITES relationships
    """
    edges: List[Tuple[int, int]] = []
    skipped = 0

    with open(cites_file, 'r') as f:
        for line in f:
            parts = line.strip().split('\t')
            if len(parts) != 2:
                continue

            cited_id, citing_id = parts

            # Verify both papers exist in our dataset
            if cited_id in paper_id_map and citing_id in paper_id_map:
                from_idx = paper_id_map[citing_id]  # Paper that cites
                to_idx = paper_id_map[cited_id]     # Paper being cited
                edges.append((from_idx, to_idx))
            else:
                skipped += 1

    if skipped > 0:
        print(f"  Warning: {skipped} edges skipped (referenced non-existent papers)")

    return edges


def write_gql_file(output_file: str, nodes: List, edges: List[Tuple[int, int]], max_features: int) -> None:
    """
    Write nodes and edges in MillenniumDB GQL import format.

    Format:
        Node: <id> :<Label> prop:value prop2:value2 list:[1, 2, 3]
        Edge: <from_id>-><to_id> :<Label> [prop:value]
    """
    os.makedirs(os.path.dirname(output_file) or '.', exist_ok=True)

    with open(output_file, 'w') as out:
        # Write header comment
        out.write(f"// Cora Dataset - Converted to MillenniumDB GQL format\n")
        out.write(f"// Nodes: {len(nodes)} papers\n")
        out.write(f"// Edges: {len(edges)} citations\n")
        out.write(f"// Features: {max_features} dimensions (of 1433 total)\n")
        out.write(f"// Classes: {len(CLASS_MAP)} categories\n")
        out.write(f"//\n")
        out.write(f"// Class mapping:\n")
        for name, idx in sorted(CLASS_MAP.items(), key=lambda x: x[1]):
            out.write(f"//   {idx}: {name}\n")
        out.write(f"//\n")
        out.write(f"// Generated by convert_cora_to_mdb.py\n")
        out.write(f"// ============================================\n\n")

        # Write nodes
        out.write(f"// NODES ({len(nodes)} papers)\n")
        for idx, paper_id, label, class_name, features in nodes:
            features_str = ', '.join(map(str, features))
            out.write(f'{idx} :Paper ')
            out.write(f'paper_id:"{paper_id}" ')
            out.write(f'label:{label} ')
            out.write(f'class_name:"{class_name}" ')
            out.write(f'features:[{features_str}]\n')

        out.write(f"\n// EDGES ({len(edges)} citations)\n")
        # Write edges (citing paper -> cited paper)
        for from_idx, to_idx in edges:
            out.write(f'{from_idx}->{to_idx} :CITES\n')


def print_statistics(nodes: List, edges: List[Tuple[int, int]]) -> None:
    """Print dataset statistics."""
    print("\n=== Cora Dataset Statistics ===")
    print(f"  Total nodes: {len(nodes)}")
    print(f"  Total edges: {len(edges)}")

    # Class distribution
    class_counts = {}
    for _, _, label, class_name, _ in nodes:
        class_counts[class_name] = class_counts.get(class_name, 0) + 1

    print("\n  Class distribution:")
    for name, count in sorted(class_counts.items()):
        pct = 100.0 * count / len(nodes)
        print(f"    {CLASS_MAP[name]}: {name}: {count} ({pct:.1f}%)")

    # Degree statistics
    out_degree = {}
    in_degree = {}
    for from_idx, to_idx in edges:
        out_degree[from_idx] = out_degree.get(from_idx, 0) + 1
        in_degree[to_idx] = in_degree.get(to_idx, 0) + 1

    avg_out = sum(out_degree.values()) / max(len(out_degree), 1)
    avg_in = sum(in_degree.values()) / max(len(in_degree), 1)
    max_out = max(out_degree.values()) if out_degree else 0
    max_in = max(in_degree.values()) if in_degree else 0

    print(f"\n  Degree statistics:")
    print(f"    Avg out-degree: {avg_out:.2f}")
    print(f"    Avg in-degree: {avg_in:.2f}")
    print(f"    Max out-degree: {max_out}")
    print(f"    Max in-degree: {max_in}")


def convert_cora(cora_dir: str, output_file: str, max_features: int = 16) -> bool:
    """
    Main conversion function.

    Args:
        cora_dir: Directory containing cora.content and cora.cites
        output_file: Output .gql file path
        max_features: Number of features to include (1-1433)

    Returns:
        True if conversion successful, False otherwise
    """
    content_file = os.path.join(cora_dir, 'cora.content')
    cites_file = os.path.join(cora_dir, 'cora.cites')

    # Verify input files exist
    if not os.path.exists(content_file):
        print(f"ERROR: Content file not found: {content_file}")
        return False
    if not os.path.exists(cites_file):
        print(f"ERROR: Cites file not found: {cites_file}")
        return False

    print(f"Converting Cora dataset to MillenniumDB GQL format...")
    print(f"  Input directory: {cora_dir}")
    print(f"  Output file: {output_file}")
    print(f"  Features per node: {max_features}")

    # Parse input files
    print("\nStep 1: Parsing nodes from cora.content...")
    paper_id_map, nodes = parse_content_file(content_file, max_features)
    print(f"  Parsed {len(nodes)} nodes")

    print("\nStep 2: Parsing edges from cora.cites...")
    edges = parse_cites_file(cites_file, paper_id_map)
    print(f"  Parsed {len(edges)} edges")

    # Write output
    print(f"\nStep 3: Writing GQL file...")
    write_gql_file(output_file, nodes, edges, max_features)
    print(f"  Written to: {output_file}")

    # Statistics
    print_statistics(nodes, edges)

    print(f"\n✓ Conversion complete!")
    print(f"\nNext steps:")
    print(f"  1. Import: build/Debug/bin/mdb import {output_file} ./data/dbs/gql/cora")
    print(f"  2. Server: build/Debug/bin/mdb server ./data/dbs/gql/cora")
    print(f"  3. Query:  curl -X POST http://localhost:1234 -H 'Content-Type: application/gql' -d 'MATCH (p:Paper) RETURN COUNT(p)'")

    return True


def main():
    # Default values
    cora_dir = '/tmp/cora_dataset/cora'
    output_file = 'cora.gql'
    max_features = 16  # Use 16 for quick tests, 1433 for full features

    # Parse command line arguments
    if len(sys.argv) > 1:
        cora_dir = sys.argv[1]
    if len(sys.argv) > 2:
        output_file = sys.argv[2]
    if len(sys.argv) > 3:
        max_features = int(sys.argv[3])
        if max_features < 1 or max_features > 1433:
            print(f"ERROR: max_features must be between 1 and 1433, got {max_features}")
            sys.exit(1)

    # Run conversion
    success = convert_cora(cora_dir, output_file, max_features)
    sys.exit(0 if success else 1)


if __name__ == '__main__':
    main()
